def ensure_seeded(store: JsonStore) -> None:
    """Создаёт демо-данные, если их ещё нет. Идемпотентно."""
    if not store.exists("users.json"):
        store.write(DEMO_USERS, "users.json")
    if not store.exists("tickets.json"):
        store.write(DEMO_TICKETS, "tickets.json")
    kb_dir = store.path("kb")
    kb_dir.mkdir(parents=True, exist_ok=True)
    if not any(kb_dir.iterdir()):
        for name, content in KB_FILES.items():
            kb_dir.joinpath(name).write_text(content, encoding="utf-8")


def kb_dir(store: JsonStore) -> Path:
    d = store.path("kb")
    d.mkdir(parents=True, exist_ok=True)
    return d
