"""Маскировка персональных данных перед отправкой в LLM.

Инвариант приватности: наружу (в DeepSeek/Ollama-cloud) уходят только
дата, сумма и обезличенное описание операции. Номера карт/счетов/договоров,
телефоны и ФИО вырезаются на этой стороне, до любого сетевого вызова.
"""
import re

# +7 977 860-89-82, +79778608982, 8 (977) 860-89-82 и т.п.
PHONE_RE = re.compile(
    r"(?:\+7|8)\s*[\(\-]?\d{3}[\)\-]?\s*\d{3}[\s\-]?\d{2}[\s\-]?\d{2}"
)
# Длинные цифровые последовательности (договоры, счета, номера карт): >= 6 цифр
LONG_NUMBER_RE = re.compile(r"\b\d{6,}\b")
# Хвосты карт вида *8010 / карта 8010 — 4 цифры после слова «карта» или звёздочки
CARD_TAIL_RE = re.compile(r"(?i)(карт[а-я]*\s*[№*]*\s*|\*)\d{4}\b")
# «Иванов И. И.» / «Иванов Иван Иванович» в описаниях переводов
FIO_RE = re.compile(
    r"\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.|\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\b"
)


def mask_text(text: str) -> str:
    """Маскирует телефоны, длинные номера, хвосты карт и ФИО в строке."""
    if not text:
        return text
    text = PHONE_RE.sub("[ТЕЛЕФОН]", text)
    text = CARD_TAIL_RE.sub(lambda m: m.group(1) + "[КАРТА]", text)
    text = LONG_NUMBER_RE.sub("[НОМЕР]", text)
    text = FIO_RE.sub("[ФИО]", text)
    return re.sub(r"\s+", " ", text).strip()


def mask_dataframe(df, column: str = "description"):
    """Маскирует колонку описаний в DataFrame транзакций (in-place копия)."""
    df = df.copy()
    df[column] = df[column].map(mask_text)
    return df
